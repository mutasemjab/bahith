مقدمة
تسعى أكاديمية ومدارس الباحث إلى توفير بيئة تعليمية آمنة، محفزة، ومبنية على الاحترام المتبادل والقيم التربوية الأصيلة. تُعد هذه المدونة مرجعاً أساسياً يحدد حقوق الطالب وواجباته، والسلوكيات المتوقعة منه، لضمان سير العملية التعليمية بأعلى درجات الانضباط والجودة.

────────────────────────────────────────
أولاً: حقوق الطالب
────────────────────────────────────────
يحق لكل طالب في أكاديمية ومدارس الباحث:

1. الحصول على بيئة تعليمية آمنة، خالية من أي شكل من أشكال التنمر أو الإساءة (اللفظية أو الجسدية).
2. التعلم في بيئة قائمة على العدالة والمساواة وتكافؤ الفرص دون تمييز.
3. التعبير عن رأيه بطريقة لائقة وأسلوب تربوي محترم.
4. الاستفادة الكاملة من كافة مرافق المدرسة (المكتبة، المختبرات، الملاعب، المنصات التعليمية) وفق الأنظمة المحددة.
5. تلقي الدعم الأكاديمي والنفسي والإرشاد التربوي عند الحاجة.

────────────────────────────────────────
ثانياً: واجبات الطالب والسلوك المتوقع
────────────────────────────────────────

1. الالتزام بالدوام والوقت

▸ الحضور والمواظبة: الالتزام بالدوام المدرسي اليومي والحضور المبكر قبل بدء الطابور الصباحي.
▸ الانضباط في الحصص: التواجد في الغرفة الصفية فور قرع الجرس وعدم التأخر عن الحصص أو التنقل بين الممرات أثناء وقت الدروس.
▸ الغياب والاستئذان: تقديم عذر خطي معتمد من ولي الأمر عند الغياب، ويُمنع مغادرة المدرسة أثناء الدوام إلا بإذن رسمي ومباشر من الإدارة.

2. المظهر العام والزي المدرسي

▸ الزي الرسمي: الالتزام التام بالزي المدرسي المعتمد لأكاديمية ومدارس الباحث بطريقة مرتبة ونظيفة.
▸ الزي الرياضي: ارتداء الزي الرياضي الخاص بالمدرسة في الأيام المحددة للحصص الرياضية فقط.
▸ النظافة والترتيب: الالتزام بالتعليمات الخاصة بالنظافة الشخصية والمظهر العام المحتشم والمناسب للبيئة المدرسية.

3. السلوك الأخلاقي والتعامل مع الآخرين

▸ احترام الكادر المدرسي: التعامل بكل أدب واحترام مع المعلمين، الإداريين، والعمال، والالتزام بتعليماتهم.
▸ الاحترام المتبادل بين الطلبة: الابتعاد التام عن الشجار، أو استخدام الألفاظ غير اللائقة، أو التنمر بأشكاله (الفعلي، اللفظي، أو الإلكتروني).
▸ الأمانة الأكاديمية: الالتزام بالنزاهة في أداء الاختبارات والواجبات، والابتعاد عن الغش أو الشروع فيه.

4. المحافظة على الممتلكات والبيئة المدرسية

▸ المرافق والأثاث: المحافظة على سلامة المقاعد الصفية، الأجهزة الذكية، مختبرات الحاسوب والعلوم، والمرافق العامة.
▸ النظافة العامة: إلقاء النفايات في الأماكن المخصصة لها والمحافظة على نظافة الساحات والغرف الصفية.

5. الأجهزة الإلكترونية والمقتنيات الثمينة

▸ الهواتف المحمولة: يُحظر استخدام أو إحضار الهواتف المحمولة أو الأجهزة الإلكترونية الشخصية إلا بإذن خاص ومسبق من الإدارة لأغراض تعليمية.
▸ المقتنيات الشخصية: المدرسة غير مسؤولة عن فقدان المقتنيات الثمينة أو المبالغ المالية الكبيرة، وتوصي بعدم إحضارها.

